import { chromium } from "playwright";
import assert from "node:assert/strict";
import { mkdir } from "node:fs/promises";
const browser = await chromium.launch({ timeout: 20000, executablePath: process.env.CHROME_PATH ?? "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome", headless: true });
const context = await browser.newContext({ viewport: { width: 390, height: 844 }, reducedMotion: "no-preference" });
await context.route(/https:\/\/.*googleapis.com\//, route => route.abort());
const page = await context.newPage();
const errors = [];
page.on("pageerror", e => errors.push(e.message));
try {
  await mkdir("artifacts", { recursive: true });
  await page.goto(new URL("/jogar", process.env.BASE_URL ?? "http://127.0.0.1:5173").href);
  await page.waitForFunction(() => window.ng?.getComponent(document.querySelector("ww-app"))?.loaded(), null, { timeout: 20000 });
  await page.evaluate(() => {
    const a = window.ng.getComponent(document.querySelector("ww-app"));
    a.receiveAccount = () => {};
    a.profile.set({ uid: "animation-test", name: "Guardião", email: "animation@example.invalid", photoURL: null });
    a.cloudStatus.set("offline");
  });
  await page.getByRole("button", { name: "Começar a jornada" }).click();
  await page.getByRole("button", { name: "Começar com" }).click();
  await page.getByRole("dialog", { name: "Escolha seu Eco inicial" }).waitFor({ state: "hidden" });
  const canvasChecks = await page.evaluate(async () => {
    const a = window.ng.getComponent(document.querySelector("ww-app"));
    const { initialGame, reduceGame, createBattle } = await import("/src/app/domain/game.ts");
    const r = a.renderer, canvas = document.querySelector("canvas");
    const g = initialGame(827361);
    g.avatar = { skin: "sand", hair: "short", hairColor: "dark", outfit: "river", accessory: "scarf" };
    const original = JSON.stringify(g);
    r.resetMotion(); r.draw(g, 1000, false, "move"); const aliveA = canvas.toDataURL();
    r.draw(g, 1500, false, "move"); const aliveB = canvas.toDataURL();
    r.resetMotion(); r.draw(g, 1000, true, "move"); const staticA = canvas.toDataURL();
    r.draw(g, 1500, true, "move"); const staticB = canvas.toDataURL();
    const moved = reduceGame(g, { type: "walk", dx: 0, dy: -1 });
    r.resetMotion(); r.draw(g, 2000, false, "move"); r.draw(moved, 2016, false, "move");
    const interpolation = r.shown.y > moved.player.y && r.shown.y < g.player.y;
    r.draw(moved, 2050, true, "move");
    const instant = r.shown.y === moved.player.y;
    const b = structuredClone(g);
    b.scene = "battle"; b.encountered = 1;
    b.battle = createBattle("local-animation", b.collection[0], "WW002", false);
    b.battle.ally.pos = { x: 2, y: 2 }; b.battle.enemy.pos = { x: 2, y: 1 };
    b.battle.plan = { destination: { x: 2, y: 1 }, action: "basic", target: { x: 2, y: 2 } };
    const command = { type: "skill", target: { x: 2, y: 1 } };
    const after = reduceGame(b, command), snapshot = JSON.stringify(after);
    r.resetMotion(); r.draw(g, 3000, false, "move"); r.draw(b, 3100, false, "skill");
    const encounter = r.enteredAt === 3100;
    r.play(b, after, command, 3200);
    r.draw(after, 3300, false, "skill"); const effectA = canvas.toDataURL();
    r.draw(after, 3600, false, "skill"); const effectB = canvas.toDataURL();
    const feedback = r.action?.feedback;
    r.draw(after, 4000, false, "skill"); const expired = r.action === null;
    r.play(b, after, command, 4200); r.draw(after, 4250, true, "skill");
    const reducedClearsEffect = r.action === null;
    const times = [];
    for (let n = 0; n < 90; n++) {
      const start = performance.now(); r.draw(g, 5000 + n * 16, false, "move"); times.push(performance.now() - start);
    }
    times.sort((a,b) => a-b);
    r.resetMotion();
    return { ambientMoves: aliveA !== aliveB, reducedStatic: staticA === staticB, interpolation, instant, encounter, effectsMove: effectA !== effectB, expired, reducedClearsEffect, feedback, immutable: original === JSON.stringify(g) && snapshot === JSON.stringify(after), medianDrawMs: times[Math.floor(times.length / 2)] };
  });
  for (const [key, value] of Object.entries(canvasChecks)) if (typeof value === "boolean") assert.ok(value, key);
  assert.equal(canvasChecks.feedback.kind, "skill");
  assert.ok(canvasChecks.feedback.enemyLoss > 0);
  await page.getByRole("button", { name: "Abrir configurações" }).click();
  await page.getByLabel("Reduzir movimento", { exact: true }).check();
  await page.waitForFunction(() => getComputedStyle(document.querySelector(".eco-symbol")).animationName === "none", null, { timeout: 10000 });
  await page.getByLabel("Reduzir movimento", { exact: true }).uncheck();
  await page.keyboard.press("Escape");
  await page.waitForFunction(() => getComputedStyle(document.querySelector(".eco-symbol")).animationName !== "none", null, { timeout: 10000 });
  await page.emulateMedia({ reducedMotion: "reduce" });
  await page.waitForFunction(() => getComputedStyle(document.querySelector(".eco-symbol")).animationName === "none", null, { timeout: 10000 });
  await page.emulateMedia({ reducedMotion: "no-preference" });
  // Real local commands still run immediately and feedback does not reserve a turn.
  await page.evaluate(async () => {
    const a = window.ng.getComponent(document.querySelector("ww-app"));
    const { createBattle } = await import("/src/app/domain/game.ts");
    const g = structuredClone(a.game());
    g.scene = "battle"; g.encountered++;
    g.battle = createBattle("local-live", g.collection[0], "WW002", false);
    g.battle.ally.pos = { x: 2, y: 2 }; g.battle.enemy.pos = { x: 2, y: 1 };
    g.battle.plan = { destination: { x: 2, y: 1 }, action: "basic", target: { x: 2, y: 2 } };
    await a.session.replaceState(g);
  });
  await page.getByRole("grid", { name: /Arena tática/ }).waitFor();
  await page.getByRole("button", { name: /Atacar/ }).click();
  await page.getByRole("gridcell", { name: /^B3,/ }).click();
  await page.waitForFunction(() => window.ng.getComponent(document.querySelector("ww-app")).game().battle.round === 2);
  await page.screenshot({ path: "artifacts/animation-battle-mobile.png", fullPage: true });
  await page.setViewportSize({ width: 1360, height: 900 });
  await page.screenshot({ path: "artifacts/animation-battle-desktop.png", fullPage: true });
  await page.evaluate(async () => {
    const a = window.ng.getComponent(document.querySelector("ww-app"));
    const { xpToNextLevel } = await import("/src/app/domain/game.ts");
    const g = structuredClone(a.game());
    g.battle.guided = true; g.battle.enemy.hp = 5;
    g.battle.ally.pos = { x: 2, y: 2 }; g.battle.enemy.pos = { x: 2, y: 1 };
    g.collection[0].experience = xpToNextLevel(1) - 1;
    await a.session.replaceState(g);
    a.prefs.update(p => ({ ...p, timing: true }));
  });
  await page.getByRole("button", { name: /Vínculo 100%/ }).click();
  await page.getByRole("heading", { name: "Ritual de Vínculo" }).waitFor();
  await page.getByRole("button", { name: /Continuar explorando/ }).waitFor();
  await page.getByRole("status").filter({ hasText: /Nível 2/ }).first().waitFor();
  assert.equal(await page.evaluate(() => window.ng.getComponent(document.querySelector("ww-app")).game().battle.result), "capture");
  assert.equal(await page.evaluate(() => window.ng.getComponent(document.querySelector("ww-app")).game().collection[0].level), 2);
  await page.screenshot({ path: "artifacts/animation-capture-level.png", fullPage: true });
  await page.getByRole("button", { name: /Continuar explorando/ }).click();
  await page.waitForFunction(() => window.ng.getComponent(document.querySelector("ww-app")).game().scene === "exploration");
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ checks: canvasChecks, errors }, null, 2));
} finally { await browser.close(); }
